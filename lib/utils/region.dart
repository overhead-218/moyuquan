WaterType waterTypeOfFish(String fish) {
  if (fish.contains('海水')) return WaterType.salt;
  if (fish.contains('淡')) return WaterType.fresh;
  for (final f in _saltwaterFish) {
    if (fish.contains(f)) return WaterType.salt;
  }
  // 默认淡水（多数内陆钓获）
  return WaterType.fresh;
}
