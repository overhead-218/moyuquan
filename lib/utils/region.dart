/// 从城市名推断大区。
/// 兼容 "广西西林" / "贵州兴义" 这类带省前缀、或直接给出县级市名的写法。
FishingRegion regionOfCity(String? city) {
  if (city == null || city.isEmpty) return FishingRegion.all;
  final trimmed = city.trim();
  // 1) 直接命中
  final direct = _cityToProvince[trimmed];
  if (direct != null) return _provinceToRegion[direct] ?? FishingRegion.all;
  // 2) 取前两字（"广西西林" → "广西"）再试
  if (trimmed.length >= 2) {
    final head = _cityToProvince[trimmed.substring(0, 2)];
    if (head != null) return _provinceToRegion[head] ?? FishingRegion.all;
  }
  return FishingRegion.all;
}

